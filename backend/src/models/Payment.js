// Payment.js — records Paystack payment attempts independently of the wallet
// ledger. A row is created as "pending" before Paystack initialization and is
// only moved to "success" by the exactly-once credit routine.
'use strict';

const { DataTypes } = require('sequelize');

module.exports = (sequelize) => {
  const Payment = sequelize.define(
    'Payment',
    {
      id: {
        type: DataTypes.INTEGER,
        primaryKey: true,
        autoIncrement: true,
      },
      userId: {
        type: DataTypes.INTEGER,
        allowNull: false,
      },
      // Internal reference generated by KoboPay. Never supplied by the client.
      reference: {
        type: DataTypes.STRING(100),
        allowNull: false,
        unique: true,
      },
      // Reference returned by Paystack. Null until initialization succeeds.
      providerReference: {
        type: DataTypes.STRING(100),
        allowNull: true,
        unique: true,
      },
      provider: {
        type: DataTypes.STRING(20),
        allowNull: false,
        defaultValue: 'paystack',
      },
      // Integer kobo only — no floating point money.
      amountKobo: {
        type: DataTypes.BIGINT,
        allowNull: false,
        validate: { min: 1 },
      },
      currency: {
        type: DataTypes.STRING(3),
        allowNull: false,
        defaultValue: 'NGN',
      },
      status: {
        type: DataTypes.STRING(20),
        allowNull: false,
        defaultValue: 'pending',
        validate: { isIn: [['pending', 'success', 'failed', 'abandoned']] },
      },
      accessCode: {
        type: DataTypes.STRING(100),
        allowNull: true,
      },
      authorizationUrl: {
        type: DataTypes.TEXT,
        allowNull: true,
      },
      paystackTransactionId: {
        type: DataTypes.BIGINT,
        allowNull: true,
      },
      channel: {
        type: DataTypes.STRING(30),
        allowNull: true,
      },
      // Optional client-supplied idempotency key, unique when present.
      idempotencyKey: {
        type: DataTypes.STRING(255),
        allowNull: true,
      },
      failureReason: {
        type: DataTypes.STRING(255),
        allowNull: true,
      },
      paidAt: {
        type: DataTypes.DATE,
        allowNull: true,
      },
      verifiedAt: {
        type: DataTypes.DATE,
        allowNull: true,
      },
      // Keep this minimal: only non-sensitive correlation data.
      metadata: {
        type: DataTypes.JSONB,
        allowNull: true,
      },
    },
    {
      tableName: 'payments',
      timestamps: true,
      indexes: [
        { fields: ['userId'] },
        { fields: ['status'] },
        { fields: ['createdAt'] },
        { fields: ['userId', 'idempotencyKey'], unique: true },
      ],
    }
  );

  return Payment;
};
